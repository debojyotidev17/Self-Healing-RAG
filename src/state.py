from typing import TypedDict, List, Optional, Dict, Any

class Citation(TypedDict):
    citation_id: int
    document_id: str
    chunk_id: str
    source: str
    relevance_score: float

class LatencyBreakdown(TypedDict):
    retrieval_ms: float
    reranking_ms: float
    generation_ms: float
    critique_ms: float
    reformulation_ms: float
    total_ms: float

class TraceInfo(TypedDict):
    trace_id: str
    latency_ms: LatencyBreakdown
    retry_count: int
    grounded: bool
    fallback: bool
    cache_hit: bool

class RAGState(TypedDict):
    """
    State dictionary tracking the lifecycle of a query through the production self-healing RAG graph.
    
    Fields:
        question: Original user query.
        reformulated_query: Rewritten search query generated when retrying.
        queries_attempted: List of all search queries executed in this run (prevents duplicate retries).
        retrieved_chunks: List of retrieved & reranked candidate document metadata dictionaries.
        answer: Candidate answer text generated by LLM.
        critique_grounded: Boolean verdict from critic LLM.
        critique_reasoning: Detailed critique reasoning from critic LLM.
        critique_confidence: Critic confidence score (0.0 to 1.0).
        critique_unsupported_claims: List of specific ungrounded claims identified by critic.
        retry_count: Current retry iteration counter (0 to max_retries).
        max_retries: Maximum allowed retries (hardcapped at 2).
        final_response: Verified grounded answer with citations or safe fallback message.
        citations: List of structured source citation metadata objects.
        trace_log: Human-readable execution timeline for UI demonstration.
        trace_info: Observability metadata dictionary containing trace_id and latency breakdown.
    """
    question: str
    reformulated_query: Optional[str]
    queries_attempted: List[str]
    retrieved_chunks: List[Dict[str, Any]]
    answer: Optional[str]
    critique_grounded: Optional[bool]
    critique_reasoning: Optional[str]
    critique_confidence: Optional[float]
    critique_unsupported_claims: List[str]
    retry_count: int
    max_retries: int
    final_response: Optional[str]
    citations: List[Citation]
    trace_log: List[str]
    trace_info: Optional[TraceInfo]
